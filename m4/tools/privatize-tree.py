#!/usr/bin/env python3
"""Take the per-unit and per-install values out of a loader source tree, so the tree can go into git.

  python3 -I m4/tools/privatize-tree.py TREE PRIVATE_DIR

TREE is a loader tree as the integrator builds it (src/standalone/gates.h, level1.h, level1-core.c, ...). The script
edits TREE in place and writes the removed text to PRIVATE_DIR (never commit that directory):

  gates-unit.h        the 4 gate records that hold this Mac's Wi-Fi calibration, module instance, antenna SKU and keyboard
                      language (gates.h gets `#include "gates-unit.h"` where they were)
  level1-install.h    L1_P4_FIRST, L1_P4_END and L1_P4_GUID_BYTES: the pinned Linux partition (level1.h and level1-core.c
                      use these macros; the values are copied verbatim)
  (shutdown-observer.c: the root file-system UUID becomes @ROOT_UUID@; the file is not in the Makefile)

The edits are textual and byte-exact: a build with PRIVATE_DIR's files copied back to TREE/src/standalone/ gives the
same objects as the unedited tree (m4/tools/verify-repo.sh proves it for rev 11, 12 and 13). Idempotent: a tree that
was already edited is left alone. Exit status 1 when a pattern is not found (a new rev changed the shape).
"""
import re, sys
from pathlib import Path

UNIT_KEYS = ['module-instance', 'wifi-antenna-sku-info', 'wifi-calibration-msf', 'kblang-calibration']


def main():
    tree, priv = Path(sys.argv[1]), Path(sys.argv[2])
    sa = tree / 'src/standalone'
    priv.mkdir(parents=True, exist_ok=True)

    # 1. gates.h
    g = (sa / 'gates.h').read_text()
    if '#include "gates-unit.h"' not in g:
        table = dict(((p, k), int(i)) for p, k, i in re.findall(r'\{"([^"]+)","([^"]+)",gate_(\d+),\d+\}', g))
        nums = sorted(i for (p, k), i in table.items() if k in UNIT_KEYS)
        assert len(nums) == 4, 'gates.h: expected 4 per-unit records, found %d' % len(nums)
        # every maximal run of consecutive private records stays where it was (the order of the arrays in .rodata is
        # part of the build), as an include of gates-unit.h that selects the run by number
        lines = g.splitlines(keepends=True)
        isp = lambda l: (re.match(r'static const unsigned char gate_(\d+)\[\]=', l) or [None, None])[1] is not None and \
            int(re.match(r'static const unsigned char gate_(\d+)\[\]=', l).group(1)) in nums
        taken, out, i = {}, [], 0
        while i < len(lines):
            if isp(lines[i]):
                run = []
                while i < len(lines) and isp(lines[i]):
                    run.append(lines[i] if lines[i].endswith('\n') else lines[i] + '\n')
                    i += 1
                ns = [int(re.match(r'static const unsigned char gate_(\d+)', l).group(1)) for l in run]
                taken.update(zip(ns, run))
                out.append('#define M4_GATES_UNIT_FROM %d /* PRIVATE: per-module values, see m4/tools/gates-unit.py */\n'
                           '#define M4_GATES_UNIT_TO %d\n#include "gates-unit.h"\n'
                           '#undef M4_GATES_UNIT_FROM\n#undef M4_GATES_UNIT_TO\n' % (min(ns), max(ns)))
            else:
                out.append(lines[i])
                i += 1
        assert sorted(taken) == nums
        (priv / 'gates-unit.h').write_text(
            '/* PRIVATE: per-module values of one Mac, generated by m4/tools/gates-unit.py. Never commit. */\n'
            + ''.join('#if M4_GATES_UNIT_FROM <= %d && %d <= M4_GATES_UNIT_TO\n%s#endif\n' % (n, n, taken[n]) for n in nums))
        (sa / 'gates.h').write_text(''.join(out))

    # 2. level1.h / level1-core.c
    h = (sa / 'level1.h').read_text()
    c = (sa / 'level1-core.c').read_text()
    if '#include "level1-install.h"' not in h:
        m1 = re.search(r'#define L1_P4_FIRST (\d+ull)[^\n]*\n#define L1_P4_END (\d+ull)\n', h)
        m2 = re.search(r'static const uint8_t P4_GUID\[16\] = (\{[^}]*\});\n', c)
        assert m1 and m2, 'level1.h / level1-core.c: pinned partition not found'
        guid = ' '.join(m2.group(1).split())
        (priv / 'level1-install.h').write_text(
            '/* PRIVATE per install: the Linux root partition Level 1 mounts (4 KiB units, [first, end)) and its PARTUUID\n'
            ' * (GPT mixed-endian bytes). Generate with m4/tools/level1-install.py. */\n'
            '#define L1_P4_FIRST %s          /* [first, end) in 4 KiB units */\n#define L1_P4_END %s\n'
            '#define L1_P4_GUID_BYTES %s\n' % (m1.group(1), m1.group(2), guid))
        h = h.replace(m1.group(0), '#include "level1-install.h" /* PRIVATE per install: L1_P4_FIRST, L1_P4_END, L1_P4_GUID_BYTES */\n')
        c = c.replace(m2.group(0), 'static const uint8_t P4_GUID[16] = L1_P4_GUID_BYTES;\n')
        c = re.sub(r'/\* PARTUUID [0-9a-f-]{36}, GPT mixed-endian bytes\. \*/', '/* PARTUUID of the pinned partition (level1-install.h), GPT mixed-endian bytes. */', c)
        (sa / 'level1.h').write_text(h)
        (sa / 'level1-core.c').write_text(c)

    # 3. the dead shutdown-observer.c: the root file-system UUID
    so = sa / 'shutdown-observer.c'
    if so.exists():
        t = so.read_text()
        t2 = re.sub(r'uuid=[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}', 'uuid=@ROOT_UUID@', t)
        if t2 != t:
            so.write_text(t2)

    # 4. .gitignore
    gi = tree / '.gitignore'
    add = ['/src/standalone/gates-unit.h', '/src/standalone/level1-install.h']
    cur = gi.read_text() if gi.exists() else ''
    new = ''.join(a + '\n' for a in add if a not in cur.split())
    if new:
        gi.write_text(cur + ('' if cur.endswith('\n') or not cur else '\n') + '# per-unit / per-install build inputs (m4/tools/privatize-tree.py)\n' + new)
    print('privatize-tree: ok; private files in', priv)


main()
