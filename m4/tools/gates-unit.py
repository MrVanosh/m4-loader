#!/usr/bin/env python3
"""Make or check src/standalone/gates-unit.h, the per-unit part of the loader's ADT admission gates.

The loader (src/standalone/metadata.c) refuses to boot unless the live ADT's bytes equal every record of gates.h.
Four of those records are per-module or per-SKU values of one Mac (Wi-Fi calibration, module instance, antenna SKU,
keyboard language), so they are not in git: gates.h includes "gates-unit.h", which you generate from a flat ADT
(the file /chosen/... of `adt.bin`, 8-byte node header, 32-byte property names, as m1n1 adt.h) of the machine:

  python3 -I m4/tools/gates-unit.py make  ADT.bin  src/standalone/gates-unit.h
  python3 -I m4/tools/gates-unit.py check ADT.bin  src/standalone/gates.h src/standalone/gates-unit.h
  python3 -I m4/tools/gates-unit.py regen ADT.bin  src/standalone/gates.h NEW-gates.h

`check` verifies that every record of gates.h plus gates-unit.h equals the ADT property (path, key, bytes). It is the
firmware-update check: after a macOS/iBoot update, rebuild the ADT file and run it; any record it names will make the
loader stop ("R21-direct STOP: guard=3") on that Mac. Output never prints values, only paths, keys and lengths.

`regen` stands in for the lost generator (tools/prepare-m4-standalone-gates.py): it rewrites every record of gates.h
(not the per-unit four) with the bytes of the same path and key in ADT.bin, for another J616s or another firmware, and
lists the records it changed. Use an ADT the loader saw: an ioreg-derived one renders 9 records differently on this Mac
(5 AAPL,unit-string, 4 PCIe bridge cell counts), and a loader built from those values would stop.
"""
import re, struct, sys

UNIT = [('/arm-io/wlan', 'module-instance'), ('/arm-io/wlan', 'wifi-antenna-sku-info'),
        ('/arm-io/wlan', 'wifi-calibration-msf'),
        ('/arm-io/dockchannel-mtp/mtp-transport/keyboard', 'kblang-calibration')]


def parse(buf):
    """flat ADT -> {path: {prop: bytes}} (the root is '/', a child is parent + '/' + its `name` property)"""
    out = {}

    def node(off, parent):
        nprops, nchild = struct.unpack_from('<II', buf, off)
        off += 8
        props = {}
        for _ in range(nprops):
            name = buf[off:off + 32].split(b'\0')[0].decode()
            size = struct.unpack_from('<I', buf, off + 32)[0] & 0x7fffffff
            props[name] = buf[off + 36:off + 36 + size]
            off += 36 + ((size + 3) & ~3)
        path = '/' if parent is None else (parent if parent != '/' else '') + '/' + props['name'].split(b'\0')[0].decode()
        out[path] = props
        for _ in range(nchild):
            off = node(off, path)
        return off
    node(0, None)
    return out


def lines(text):
    return {int(m.group(1)): m.group(0) for m in re.finditer(r'static const unsigned char gate_(\d+)\[\]=\{[^}]*\};', text)}


def table(text):
    return [(p, k, int(i), int(n)) for p, k, i, n in re.findall(r'\{"([^"]+)","([^"]+)",gate_(\d+),(\d+)\}', text)]


def c_array(i, data):
    return 'static const unsigned char gate_%d[]={%s};' % (i, ','.join('0x%x' % b for b in data))


def main():
    mode, adtfile = sys.argv[1], sys.argv[2]
    adt = parse(open(adtfile, 'rb').read())
    if mode == 'make':
        # needs the gates.h table to learn the gate numbers: python3 gates-unit.py make ADT OUT [gates.h]
        out = sys.argv[3]
        tbl = table(open(sys.argv[4] if len(sys.argv) > 4 else 'src/standalone/gates.h').read())
        res = []
        for p, k, i, n in tbl:
            if (p, k) in UNIT:
                v = adt[p][k]
                assert len(v) == n, (p, k, len(v), n)
                res.append((i, c_array(i, v)))
        assert len(res) == len(UNIT), 'gate records missing in gates.h'
        open(out, 'w').write('/* PRIVATE: per-module values of one Mac, generated by m4/tools/gates-unit.py. Never commit. */\n'
                             + ''.join('#if M4_GATES_UNIT_FROM <= %d && %d <= M4_GATES_UNIT_TO\n%s\n#endif\n' % (n, n, r)
                                       for n, r in sorted(res)))
        print('wrote %s: %d records' % (out, len(res)))
    elif mode == 'check':
        text = open(sys.argv[3]).read() + '\n' + open(sys.argv[4]).read()
        tbl, arr = table(text), lines(text)
        bad = 0
        for p, k, i, n in tbl:
            v = adt.get(p, {}).get(k)
            want = None
            if i in arr:
                want = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)', arr[i].split('=', 1)[1]))
            if v is None or want is None or v != want or len(v) != n:
                bad += 1
                print('MISMATCH gate_%d %s %s (adt %s B, gate %s B)' % (i, p, k, None if v is None else len(v), n))
        print('%d gate records, %d mismatch' % (len(tbl), bad))
        sys.exit(1 if bad else 0)
    elif mode == 'regen':
        text = open(sys.argv[3]).read()
        arr, changed, missing = lines(text), 0, 0
        for p, k, i, n in table(text):
            if (p, k) in UNIT:
                continue
            v = adt.get(p, {}).get(k)
            if v is None:
                missing += 1
                print('kept    gate_%d %s %s: not in this ADT (an ioreg dump lacks AAPL,unit-string; use a native ADT)' % (i, p, k))
                continue
            new = c_array(i, v)
            if new != arr[i] or len(v) != n:
                changed += 1
                print('changed gate_%d %s %s (%d -> %d B)' % (i, p, k, n, len(v)))
            text = text.replace(arr[i], new).replace('{"%s","%s",gate_%d,%d}' % (p, k, i, n), '{"%s","%s",gate_%d,%d}' % (p, k, i, len(v)))
        open(sys.argv[4], 'w').write(text)
        print('wrote %s: %d records changed, %d kept (missing)' % (sys.argv[4], changed, missing))
        sys.exit(1 if missing else 0)


main()
